"""Инструкции и JSON Schema для разбора загруженного документа.

Две стадии map-reduce:
  MAP    — DOC_CHUNK_INSTRUCTIONS + DOC_CHUNK_SCHEMA: разбор ОДНОГО фрагмента;
  REDUCE — DOC_CARD_INSTRUCTIONS + DOC_CARD_SCHEMA: карточка ВСЕГО документа из
           результатов фрагментов.

Схемы уходят в клиента с `"strict": True` (см. processing/openai_client.py), поэтому
здесь только те ключевые слова, что строгий режим принимает: type, enum, properties,
required, additionalProperties, items. Никаких minItems/minimum — диапазоны («5-7
пунктов», «anchor из диапазона фрагмента») живут в тексте инструкции, а числовые
границы проверяет наш собственный валидатор, а не схема.

Документ — не статья: у него нет источника и URL, зато есть место в тексте (страница,
слайд, блок), на которое обязан ссылаться каждое извлечённое число.
"""

from __future__ import annotations


# Вход MAP-стадии формирует пайплайн: текст фрагмента с номерами якорей и явно
# названным диапазоном. Инструкция описывает этот вход словами, чтобы модель знала,
# откуда брать anchor, и чтобы формат входа не расходился с ожиданием молча.
DOC_CHUNK_INSTRUCTIONS = """Ты аналитик, разбирающий ФРАГМЕНТ делового документа (отчёт,
презентация, статья, коммерческое предложение). Во входе — текст фрагмента и диапазон его
якорей: страниц, слайдов или блоков. Перед каждым куском текста стоит номер якоря, из
которого этот кусок взят.

Верни две вещи.

1. about — одна-две фразы по-русски: о чём именно ЭТОТ фрагмент. Не пересказ первых строк,
а суть куска. Фрагмент служебный (титул, оглавление, контакты, дисклеймер, список литературы)
— так и напиши, это полезнее выдуманного содержания.

2. facts — величины, извлечённые из фрагмента. Каждый факт:
- value — число РОВНО как в тексте, посимвольно: «12,5», «1 200», «3.4», «около 40». Не меняй
  разделители, не переставляй запятую на точку, не убирай пробелы внутри числа.
- unit — единица ВМЕСТЕ с масштабом: «млн тонн», «%», «руб/т», «млрд руб.», «тыс. м3», «шт.».
  Масштаб — часть единицы: «млн» из фразы «12,5 млн тонн» относится к unit, а не к value.
  Величина безразмерная (количество, номер, год) — верни пустую строку.
- context — короткая фраза, ЧТО именно это за величина, НА ЯЗЫКЕ ОРИГИНАЛА документа:
  документ английский — контекст английский, русский — русский. Не переводи и не обобщай:
  «добыча нефти в 2024 г.», «CAPEX программы», «срок окупаемости проекта».
- anchor — номер якоря, откуда взята величина. ОБЯЗАН попадать в диапазон фрагмента,
  указанный во входе. Не видишь точно, из какого якоря число, — выброси факт целиком;
  номер «примерно» бесполезен, потому что пользователь пойдёт по нему в документ.

ЗАПРЕЩЕНО: считать (суммы, разности, доли, темпы роста, средние), пересчитывать единицы
(тонны в баррели, доллары в рубли, месяцы в годы), округлять, дополнять число из общих знаний
о рынке или компании. В выдаче могут быть ТОЛЬКО те числа, которые буквально напечатаны во
фрагменте.

Числовых величин во фрагменте нет — верни пустой список. Это нормальный и правильный ответ:
пустота честна, а придуманное число будет показано пользователю со ссылкой на конкретную
страницу и подорвёт доверие ко всей карточке.

Ответ строго по JSON Schema."""


# Вход REDUCE-стадии — результаты всех MAP-фрагментов по порядку. Своего доступа к
# документу у модели на этой стадии нет, и инструкция говорит об этом прямо: иначе
# свёртка дописывает «типовой» отраслевой текст поверх того, что реально прочитано.
DOC_CARD_INSTRUCTIONS = """Ты отраслевой аналитик. Во входе — разборы всех фрагментов ОДНОГО
документа, по порядку: краткое «о чём» каждого фрагмента и извлечённые из него величины с
номерами якорей (страниц, слайдов, блоков). Собери из них карточку документа. Другого доступа
к документу у тебя нет: чего нет во входе — того нет и в карточке.

passport — паспорт документа:
- doc_type — тип: «отчёт», «презентация», «статья», «КП» (коммерческое предложение) или
  «иное». Суди по содержанию и построению, а не по числу фрагментов.
- publisher — организация или издание, выпустившее документ. Не названо во входе —
  «не указано». Не угадывай издателя по теме.
- date — дата документа так, как она указана в нём («2024», «март 2025», «12.03.2025»).
  Не названа — «не указано». Дату не выводи из упомянутых в тексте годов.
- language — основной язык документа: «русский», «английский» или другой, одним словом.

essence — СУТЬ: 2-3 предложения. Что это за документ и зачем он выпущен: кто автор, о чём и
для кого. Без маркетинга и без оценок «важный», «интересный».

summary — СВОДКА: 5-7 пунктов ПО РАЗДЕЛАМ документа. Пункты обязаны покрывать документ от
первого фрагмента до последнего — не пересказывай начало и не оставляй хвост документа
неохваченным. Каждый пункт — законченная мысль в одно-два предложения, а не заголовок раздела.
Числа в пунктах — только те, что есть во входных фактах, и в той же форме.

claims — заявления документа, которые НЕ подкреплены фактами: «лидер рынка», «уникальная
технология», «повышает эффективность», «сокращает сроки» — там, где ни цифры, ни расчёта,
ни ссылки на измерение. Вендорские материалы наполовину состоят из маркетинга, и карточка
обязана отделять то, что документ ДОКАЗЫВАЕТ, от того, что он УТВЕРЖДАЕТ. Это не критика
документа и не спор с ним: просто перечисли такие заявления, коротко, своими словами.
Нечего вынести — пустой список.

Пиши ТОЛЬКО на грамотном русском, даже если документ английский. Запрещены иностранные слова,
буквы и случайные символы ВНУТРИ русских слов («многоAgentная», «térмальный» — нельзя).
Латиница — лишь для общепринятых аббревиатур (SCADA, EOR, CCS, LNG) и имён собственных;
английские термины переводи (offshore → шельф, workover → капитальный ремонт скважин).

Не досочиняй: ни выводов, которых в документе нет, ни чисел, которых нет во входных фактах,
ни «отраслевого контекста» из своих общих знаний. Входные разборы противоречат друг другу —
опиши то, что есть, не сглаживая противоречие выдуманной серединой.

Ответ строго по JSON Schema."""


DOC_CHUNK_SCHEMA = {
    "name": "document_chunk",
    "schema": {
        "type": "object",
        "additionalProperties": False,
        "required": ["about", "facts"],
        "properties": {
            "about": {"type": "string"},
            "facts": {
                "type": "array",
                "items": {
                    "type": "object",
                    "additionalProperties": False,
                    "required": ["value", "unit", "context", "anchor"],
                    "properties": {
                        "value": {"type": "string"},
                        "unit": {"type": "string"},
                        "context": {"type": "string"},
                        "anchor": {"type": "integer"},
                    },
                },
            },
        },
    },
}

DOC_CARD_SCHEMA = {
    "name": "document_card",
    "schema": {
        "type": "object",
        "additionalProperties": False,
        "required": ["passport", "essence", "summary", "claims"],
        "properties": {
            "passport": {
                "type": "object",
                "additionalProperties": False,
                "required": ["doc_type", "publisher", "date", "language"],
                "properties": {
                    # Строгий режим требует все поля в required, поэтому «неизвестно»
                    # выражено значением «не указано», а не отсутствием ключа:
                    # рендеру карточки не приходится разбирать None.
                    "doc_type": {
                        "type": "string",
                        "enum": ["отчёт", "презентация", "статья", "КП", "иное"],
                    },
                    "publisher": {"type": "string"},
                    "date": {"type": "string"},
                    "language": {"type": "string"},
                },
            },
            "essence": {"type": "string"},
            "summary": {"type": "array", "items": {"type": "string"}},
            "claims": {"type": "array", "items": {"type": "string"}},
        },
    },
}
