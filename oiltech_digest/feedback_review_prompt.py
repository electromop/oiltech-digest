"""Промпт агента «Разбор ОС» по сигналу (#189, спека #187; отклики потребителя выпуска: #200, спека #197): задача, поля
и допустимые значения, схема ответа и вход модели о сигнале. Строит его воркер NL из пакета задачи
(feedback_review.process_payload); ядро проверяет ответ кодом (feedback_review.checked_changes).

Отклики потребителя: кнопки, нажатые его сотрудниками на карточке, без текста и без автора. В ответе на них ссылается
отдельный список reactions рядом с номерами отметок; цитатой служит подпись кнопки.
"""

from __future__ import annotations

from typing import Any

from oiltech_digest import feedback_changes

_TASK = """Ты разбираешь обратную связь людей по одной карточке сигнала рынка нефтесервиса. Во входе: поля карточки,
текст главной публикации, все отметки людей платформы по этой карточке за последние недели (оценка, обоснование,
рекомендации, предложенные заголовок и суть, номер главной карточки «Дубля») и отклики сотрудников потребителя выпуска:
кнопки, которые они нажали на карточке, без текста («Не про нефтесервис», «Ошибка в карточке», «Не новое», «Мало
фактов»). Сведи отметки и отклики в одно улучшение карточки: какие её поля поменять и на что. Сам ты ничего не меняешь:
улучшение согласует администратор.

Правила:
- Меняй поле, только если это прямо следует из отметок и откликов. quote: дословный фрагмент текста одной из отметок
  или подпись кнопки отклика, на которых стоит изменение (marks: номера отметок, reactions: номера откликов). Без такой
  цитаты поле не предлагай.
- Отклик без текста сам не говорит, что исправить: поле по отклику предлагай, только если из карточки и публикации
  видно, что именно в ней неверно или чего не хватает.
- Значения полей со списком (тема, тип события, стадия, регион, класс технологии, категория): только из списков ниже,
  дословно. Страны и компании: через «;». Дата события: ГГГГ-ММ-ДД, ГГГГ-ММ или ГГГГ.
- Похожие отметки сводятся в одно значение. Если отметки противоречат друг другу и из текста не ясно, что верно, поле
  не предлагай. Значение, которое уже стоит в карточке, не предлагай.
- Заголовок и суть: если люди предлагают свой текст, дай один текст, сведённый из их предложений, по-русски. Короткая
  строка-описание поверх развёрнутой сути не улучшение: развёрнутую суть не заменяй.
- Категорию меняй, только если есть отметка «Не тот блок»; «Дубль» (номер главной карточки), только если есть отметка
  «Дубль» с этим номером; «убрать», только если есть отметка «Не релевантно». Отклики потребителя категорию, «Дубль»
  и уборку не обосновывают.
- Каждое поле не больше одного раза. Улучшать нечего: пустой список."""


def instructions(choices: dict[str, list[str]]) -> str:
    lines = [_TASK, "", "Поля (field) и допустимые значения:"]
    for field, spec in feedback_changes.FIELDS.items():
        listed = choices.get(field)
        hint = f": {'; '.join(listed)}" if listed else {"text": ": свободный текст", "date": ": дата",
                                                         "countries": ": страны через «;»",
                                                         "companies": ": компании через «;»",
                                                         "duplicate": ": номер главной карточки",
                                                         "removal": ": «да»"}.get(spec.kind, "")
        lines.append(f"- {field} ({spec.label}){hint}")
    return "\n".join(lines)


def answer_schema() -> dict[str, Any]:
    return {"name": "feedback_review", "schema": {
        "type": "object", "additionalProperties": False, "required": ["improvements"],
        "properties": {"improvements": {"type": "array", "items": {
            "type": "object", "additionalProperties": False,
            "required": ["field", "value", "marks", "reactions", "quote"],
            "properties": {"field": {"type": "string", "enum": list(feedback_changes.FIELDS)},
                           "value": {"type": "string"},
                           "marks": {"type": "array", "items": {"type": "integer"}},
                           "reactions": {"type": "array", "items": {"type": "integer"}},
                           "quote": {"type": "string"}},
        }}},
    }}


def model_input(item: dict[str, Any]) -> str:
    """Вход модели о сигнале: карточка, публикация, отметки без имён авторов и отклики потребителя."""
    card = item.get("card") or {}
    lines = [f"Карточка №{item.get('signal_id')}", *[f"{label}: {value or 'не определено'}"
                                                    for label, value in card.items()]]
    publication = item.get("publication") or {}
    lines += ["", f"Публикация: {publication.get('title') or ''}", publication.get("text") or "", "", "Отметки людей:"]
    for mark in item.get("marks") or []:
        lines.append(f"Отметка №{mark['id']} ({mark['role']}, {mark['day']}):")
        for label, key in (("Оценка", "verdict"), ("Обоснование оценки", "reason"),
                           ("Рекомендации AI-агенту", "comment"), ("Предложенный заголовок", "proposed_title"),
                           ("Предложенная суть", "proposed_summary")):
            if mark.get(key):
                lines.append(f"  {label}: {mark[key]}")
        if mark.get("duplicate_of"):
            lines.append(f"  Дубль: главная карточка №{mark['duplicate_of']}")
        if mark.get("applied") and mark.get("role") == "администратор":
            lines.append("  (явные действия этой отметки уже применены)")
    reactions = item.get("reactions") or []
    if reactions:
        lines += ["", "Отклики сотрудников потребителя (кнопки на карточке, без текста):",
                  *[f"Отклик №{one['id']} ({one['role']}, {one['day']}): {one['reaction']}" for one in reactions]]
    return "\n".join(lines)
