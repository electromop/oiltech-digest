-- Контур ОС (#188): одна форма ОС и явные действия администратора: схема ДО выката кода ядра, который её читает.
--
-- Только добавления, повторный прогон безопасен (IF NOT EXISTS), заполнений нет. Таблицы не переписываются: значение
-- по умолчанию у applied постоянное (Postgres 11+ хранит его в каталоге), у human_removal его нет. Прежние отметки
-- остаются применёнными: их правки заголовка и сути на карточках и в выпусках не меняются.
-- lock_timeout: ALTER берёт на таблицах эксклюзивный замок; если его держит долгий запрос, шаг откажет через 5 с, ничего
-- не изменив: повторить позже. Окно: не во время радара (00:00-02:30 МСК).
--
--   ssh <РФ-ядро> 'docker exec -i oiltech_pg psql -U oiltech -d oiltech_digest -X -v ON_ERROR_STOP=1' \
--     < scripts/signals/os-form-before-deploy.sql
BEGIN;
SET LOCAL lock_timeout = '5s';
-- Явные действия отметки применены сразу (отметка администратора, правка материала); FALSE: отметка участника без прав
-- администратора, только записана и видна блоком.
ALTER TABLE signal_feedback_events ADD COLUMN IF NOT EXISTS applied BOOLEAN NOT NULL DEFAULT TRUE;
-- «Убрано людьми»: прежнее решение «Отбора» (его возвращает «вернуть»), кто, когда и почему.
ALTER TABLE signals ADD COLUMN IF NOT EXISTS human_removal JSONB;
COMMIT;
