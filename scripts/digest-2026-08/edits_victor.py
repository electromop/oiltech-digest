def apply_title(num: int, title: str) -> str:
    rule = TITLE_EDITS.get(num)
    if not rule:
        return title
    was, now, why = rule
    if title != was:
        raise SystemExit(
            f"Правка заголовка №{num} не применилась — исходный текст не совпал.\n"
            f"  ожидал: {was!r}\n  получил: {title!r}\n  основание: {why}"
        )
    return now


def apply_summary(num: int, summary: str) -> str:
    for was, now, why in SUMMARY_EDITS.get(num, []):
        if was not in summary:
            raise SystemExit(
                f"Правка текста №{num} не применилась — фрагмент не найден.\n"
                f"  искал: {was!r}\n  в тексте: {summary!r}\n  основание: {why}"
            )
        summary = summary.replace(was, now)
    return summary
